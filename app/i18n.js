let currentLang = 'en';

export function setLang(lang) {
  currentLang = STRINGS[lang] ? lang : 'en';
  // Guarded so the string layer also works in Node (tests, SSG).
  if (typeof document !== 'undefined') document.documentElement.setAttribute('lang', currentLang);
  return currentLang;
}

export function getLang() {
  return currentLang;
}

/** t('win.title', { name: 'Aarav' }) — falls back to English, then to the key. */
export function t(key, vars = {}) {
  const dict = STRINGS[currentLang] || STRINGS.en;
  let text = dict[key] ?? STRINGS.en[key] ?? key;
  Object.keys(vars).forEach((k) => {
    text = text.replaceAll(`{${k}}`, String(vars[k]));
  });
  return text;
}

export default t;
